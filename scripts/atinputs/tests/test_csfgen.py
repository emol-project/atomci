from ..constants import ATG_SGSHL_DEFAULT
from ..csfgen import generate_csf
from ..csfgen.excite import generate_doubles, generate_singles
from ..csfgen.refgen import build_references, build_shell_table
from ..parser import parse_file
from ..schema import validate


def _load(atinputs_dir, name):
    path = str(atinputs_dir / f'{name}.inp')
    return validate(parse_file(path), path)


def test_f_shell_table(atinputs_dir):
    data = _load(atinputs_dir, 'f')
    table = build_shell_table(data)
    labels = [s.label for s in table.shells]
    assert labels == ['2S', 'NS', '2P', 'NP', 'ND', 'NF']
    assert [s.capacity for s in table.shells] == [2, 22, 6, 60, 60, 70]


def test_f_reference(atinputs_dir):
    data = _load(atinputs_dir, 'f')
    table = build_shell_table(data)
    refs = build_references(data, table)
    assert len(refs) == 1
    assert refs[0].occ == [2, 0, 5, 0, 0, 0]


def test_f_excitation_counts(atinputs_dir):
    data = _load(atinputs_dir, 'f')
    table = build_shell_table(data)
    refs = build_references(data, table)
    singles = generate_singles(refs, table)
    doubles = generate_doubles(singles, table)
    assert len(refs) == 1
    assert len(singles) == 10  # 1 reference + 9 distinct singles
    assert len(doubles) == 28  # + 18 distinct doubles


def test_f_matches_frozen_reference_csf(atinputs_dir, reference_dir):
    data = _load(atinputs_dir, 'f')
    text = generate_csf(data, ATG_SGSHL_DEFAULT)
    assert text == (reference_dir / 'f.atgen.csf').read_text()


def test_fpt_matches_frozen_reference_csf(atinputs_dir, reference_dir):
    data = _load(atinputs_dir, 'fpt')
    text = generate_csf(data, ATG_SGSHL_DEFAULT)
    assert text == (reference_dir / 'fpt.atgen.csf').read_text()


def test_singles_have_no_parity_filter_at_generation(atinputs_dir):
    # 2S(even)->virtual-P(odd) IS generated by ATSGEN (no filter there) even
    # though it's never selected for printing (marker<0 fails ATPRNT's gate).
    data = _load(atinputs_dir, 'f')
    table = build_shell_table(data)
    refs = build_references(data, table)
    singles = generate_singles(refs, table)
    np_idx = table.index('NP')
    assert any(s.occ[np_idx] == 1 and s.parity_marker < 0 for s in singles[len(refs):])


def test_doubles_marker_always_zero(atinputs_dir):
    # ATDGEN zeroes the marker row for every new double (src/atlib.f:472-473)
    data = _load(atinputs_dir, 'f')
    table = build_shell_table(data)
    refs = build_references(data, table)
    singles = generate_singles(refs, table)
    doubles = generate_doubles(singles, table)
    assert all(c.parity_marker == 0 for c in doubles[len(singles):])
