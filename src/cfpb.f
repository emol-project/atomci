      SUBROUTINE SYMTLZ(LFX)
      IMPLICIT  DOUBLE PRECISION (A-H,O-Z)
      REAL    EPS
      COMMON   ACOMM(8000),ICOMM(2041)
      DIMENSION CMTTBL(8000),ILFUNC(600)
      EQUIVALENCE (ICOMM( 942),ILFUNC(1))
      EQUIVALENCE (ACOMM(   1),CMTTBL(1))
      DIMENSION C(490),B(490),X(49),D(490),ITST(10),AUX(20),AC(490)
      DIMENSION IADRS(490),IADRDS(490),IPARS(490),IPARDS(490)
      LFO=LFX
      EPS=1.0D-10
      DO 1 ISXT=1,LFO,2
      ISST=LFO+2-ISXT
      DO 2 IMXT=2,ISST,2
      RMAXV=0.0D0
      IMU=IMXT/2
      ISP=ISST-IMU+1
      IF(ISP.EQ.LFO+1) GO TO 2
      IPNA=0
      IF(IMU.NE.1) IPNA=1
      IPNB=0
      IF(ISXT.NE.1) IPNB=1
