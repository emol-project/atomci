      SUBROUTINE CONVT(SLES,NHLF,NHST,NHWN,NHWQ,NHWCSL,NHVN,NHVQ,NHVCSL,
     *       I,J,NHT,NOE, ITEST)
C                                 CHECKED TASHI 10/25/89 HUCC
      IMPLICIT REAL*8(A-H,O-Z)
      DIMENSION F(41),NHLF(*)
      DIMENSION NHST(*)
      DIMENSION NHWN(*),NHWQ(*),NHWCSL(*),NHVN(*),NHVQ(*),NHVCSL(*)
      FSUBK(L,L1,L2,L3,L4)=DFLOAT(1-2*IABS(MOD((L1-L2+L3-L4+88)/4,2)))*
     1 DSQRT(DFLOAT(L1*L2*L3*L4)/DFLOAT(L))*F3L(L,L1,L2)*F3L(L,L3,L4)
C
      LFI=NHLF(I)
      LFJ=NHLF(J)
      T11= WIG6J(2,2,1,2,2,1)
      T13= WIG6J(2,2,3,2,2,1)      *DSQRT(3.0D0)
      KMIN=IABS(LFI-LFJ)+1
      KMAX=LFI+LFJ-1
      KT=(KMAX-KMIN)/2+1
      DO 142 KST=1,KT
      KM=2*KST-1
      CALL SHMS(NHLF,NHST,NHWN,NHWQ,NHWCSL,NHVN,NHVQ,NHVCSL,
     *   ITEST, I,I,1,KM,J,J,1,KM,1,1,NHT,W)
      IF(MOD(KST,2).EQ.0) GO TO 143
      IF(DABS(W).LT.SLES) GO TO 143
      NOE=NOE+1
      WT     =FSUBK(KM,LFI,LFI,LFJ,LFJ)*W*2.0D0
      CALL ISQT(KM,I,I,J,J,NOE,WT)
  143 CALL SHMS(NHLF,NHST,NHWN,NHWQ,NHWCSL,NHVN,NHVQ,NHVCSL,
     *   ITEST, I,I,3,KM,J,J,3,KM,1,1,NHT,WA)
      F(KST)=T11*W+T13*WA
  142 CONTINUE
      KTA=(KT+1)/2
      KM=KMIN
      DO 182 KST=1,KTA
      W=0.0D0
      DO 183 KMT=1,KT
      KMM=KMT*2-1
  183 W=W+F(KMT)*DSQRT(DFLOAT(KM*KMM))*WIG6J(LFI,LFI,KMM,LFJ,LFJ,KM)
      IF(DABS(W).LT.SLES) GO TO 182
      NOE=NOE+1
      WT     =FSUBK(KM,LFI,LFJ,LFJ,LFI)*W*2.0D0
      CALL ISQT(KM,I,J,J,I,NOE,WT)
  182 KM=KM+4
      RETURN
      END
