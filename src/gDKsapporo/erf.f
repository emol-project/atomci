C     ------------------------
      REAL*8 FUNCTION ERF( X )
C     ------------------------
C*
C*****************************************************
C*                 error function                    *
C*              in double precision                  *
C*      COPYRIGHT : M.Mori  AUG. 30 1990  V.1-2	    *
C*****************************************************
      IMPLICIT REAL*8 (A-H,O-Z)
C*
      PARAMETER (NM = 5, NX = 13, NA = 5)
C*
      DIMENSION CM(0:NM),CX(NX),CQ(NX),CA(0:NA)
C*
      PARAMETER (PH = 1.7724 53850 90551 6 D0)
      PARAMETER (CMC = 2 / PH)
      PARAMETER (H = 0.5D0)
      PARAMETER (CXC = 2 * H / 3.1415 92653 58979 3 D0)
      PARAMETER (CXI = 4 / CXC)
C*
      DATA CM /
     $   0.1000000000000000D+01,
     $  -0.3333333333333333D+00,
     $   0.1000000000000000D+00,
     $  -0.2380952380952381D-01,
     $   0.4629629629629630D-02,
     $  -0.7575757575757575D-03 /
C*
      DATA CX /
     $   0.7788007830714048D+00,
     $   0.3678794411714423D+00,
     $   0.1053992245618643D+00,
     $   0.1831563888873418D-01,
     $   0.1930454136227709D-02,
     $   0.1234098040866796D-03,
     $   0.4785117392129009D-05,
     $   0.1125351747192591D-06,
     $   0.1605228055185612D-08,
     $   0.1388794386496402D-10,
     $   0.7287724095819692D-13,
     $   0.2319522830243569D-15,
     $   0.4477732441718302D-18 /
      DATA CQ /
     $   0.2500000000000000D+00,
     $   0.1000000000000000D+01,
     $   0.2250000000000000D+01,
     $   0.4000000000000000D+01,
     $   0.6250000000000000D+01,
     $   0.9000000000000000D+01,
     $   0.1225000000000000D+02,
     $   0.1600000000000000D+02,
     $   0.2025000000000000D+02,
     $   0.2500000000000000D+02,
     $   0.3025000000000000D+02,
     $   0.3600000000000000D+02,
     $   0.4225000000000000D+02 /
C*
      DATA CA /
     $   0.1000000000000000D+01,
     $  -0.1000000000000000D+01,
     $   0.3000000000000000D+01,
     $  -0.1500000000000000D+02,
     $   0.1050000000000000D+03,
     $  -0.9449999999999999D+03 /
C*
      IF (X .GE. 0) THEN
        XV = X
      ELSE
        XV = -X
      END IF
C*
      IF (XV .LE. 0.1D0) THEN
        Y = XV**2
        V = CM(NM)
        DO 10 I = NM - 1, 0, -1
          V = CM(I) + Y * V
   10   CONTINUE
        ERF = CMC * XV * V
        RETURN
C*
      ELSE IF (XV .LE. 100.0D0) THEN
        Y = XV**2
        V = 1 / (2 * Y)
        DO 20 I = 1, NX
          V = V + CX(I) / (CQ(I) + Y)
   20   CONTINUE
        V = CXC * XV * EXP(-Y) * V
        IF (XV .LT. 6.0D0) THEN
          V = V - 2 / (EXP(CXI * XV) - 1)
        END IF
        ERF = 1 - V
C*
      ELSE
	Y = 1 / (2 * XV**2)
        V = CA(NA)
        DO 30 I = NA - 1, 0, -1
          V = CA(I) + Y * V
   30   CONTINUE
        V = EXP(-XV**2) / (PH * XV) * V
        ERF = 1 - V
      END IF
C*
      IF (X .GE. 0) THEN
        RETURN
      ELSE
        ERF = -ERF
        WRITE (6,2001) X
 2001   FORMAT (' (FUNC.ERF) invalid argument',
     $          ' X =',D23.16,' (warning only)')
        RETURN
      END IF
C*
      END
