      FUNCTION LSQNFP(LAD,L,IS,IQ)
      DIMENSION LAD(21)
      M=(L+1)/2
      LSQNFP=LAD(M)+(L*(L+6-2*IQ)+IQ*(IQ-6)-2*IS+8)/4
C     if (debug) WRITE (6,*) ' LSQNFP,L,IS,IQ=', LSQNFP,L,IS,IQ
      RETURN
      END
      SUBROUTINE NORMFP(W,IMU,I,J,IS,IR)
      IMPLICIT   DOUBLE PRECISION (A-H,O-Z)
C*****  CALCULATE  OVERLAP OF  A*PSI(I) AND A*PSI(J) COUPLED TO
C       IS,IR   AND IMU-1  *****
C*****  QUASI SPIN OF PSI/S ARE IMU  *****
      COMMON/AA/CFP(   88,88),ISP(88,88),IORB(88,88),INUM(88),IMUMAX,
     1  ISPSHL,LSHELL
      Z(I)=DBLE((-1)**(I/2))
      ISI=ISP(IMU,I)
      ISJ=ISP(IMU,J)
      IRI=IORB(IMU,I)
      IRJ=IORB(IMU,J)
      W2=WIG6J(IMU,2,IMU-1,IMU,2,IMU+1)*DBLE(IMU-1)
      W1=WIG6J(IMU,2,IMU+1,IMU,2,IMU+1)/DBLE(IS*IR)
      W=0.0D0
      IF(I.NE.J) GO TO 10
      W=Z(2*IMU)
   10 IF(IMU.NE.IMUMAX) GO TO 11
      W=W/W2
C9000 WRITE(6,*) ' 10  W1,W2,W=',W1,W2,W
      RETURN
   11 WSP=0.0D0
      WG=0.0D0
      KMAX=INUM(IMU+1)
      DO 20 K=1,KMAX
      A=CFP(    I,K)*CFP(    J,K)
      IF(A.EQ.0.0D0) GO TO 20
      ISK=ISP(IMU+1,K)
      IRK=IORB(IMU+1,K)
      IF(ISK.EQ.IS.AND.IRK.EQ.IR) WSP=WSP+A
      H=WIG6J(ISI,ISPSHL,IS,ISJ,ISPSHL,ISK)
      IF(H.EQ.0.0D0 ) GO TO 20
      H=H*WIG6J(IRI,LSHELL,IR,IRJ,LSHELL,IRK)
      IF(H.EQ.0.0D0) GO TO 20
      WG=WG+H*A
   20 CONTINUE
      W=(W+Z(ISI+IRI-ISJ-IRJ+1002)*(W1*WSP+WG*Z(2*(IMU+IS+IR))
     1                   /DBLE(IMU+1)))/W2
C9001 WRITE(6,*) ' 20  W1,W2,W=',W1,W2,W
      RETURN
      END
      LOGICAL FUNCTION FINDFP(I,J,K)
      FINDFP=.FALSE.
      IF( MOD(I+J+K,2).EQ.0) RETURN
      IF(I+J-K.LT.1.OR.IABS(I-J).GT.K-1) RETURN
      FINDFP=.TRUE.
      RETURN
      END
