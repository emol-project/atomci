     1   3HAM=,6I3,6H *****///)
   20 WIG6J=0.0D0
      RETURN
    1 IF (IB.NE.IC.OR.IE.NE.IV)  GO TO 20
      IF (DELTA(ID,IE,IC).EQ.0.0D0) GO TO 20
      WIG6J=ZIZ(ID+IE+IC)/(RT(IB+1)*RT(IE+1))
