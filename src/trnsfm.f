C*DECK TRNSFM
      SUBROUTINE TRNSFM (NORB,NTABC,C,NFTA,NFTB,NFD,LPRD,LDSK,
     1                   NCOR,CR,NFLGS,NALM)
C                                 CHECKED TASHI 10/25/89 AT HUCC
      IMPLICIT REAL*8 (A-H,O-Z)
      COMMON  IDSK
      DIMENSION NORB(*),NTABC(*),C(*),CR(*)
C
      NTDRG  = LDSK

   50 CONTINUE
      READ (NFTA,END=900) ML,MS1,MS2,MS3,MS4,NP,NQ,NR,NS,
     1                    NPQ,NRS,NCODI,NCODA,NCODB
C
      MP=NORB(MS1+1)
      MQ=NORB(MS2+1)
      MR=NORB(MS3+1)
      MS=NORB(MS4+1)
C
      MPQ=MP*MQ
      IF (NCODA.EQ.3) MPQ=(MP*(MP+1))/2
      MRS=MR*MS
      IF (NCODB.EQ.3) MRS=(MR*(MR+1))/2
      IF (MPQ*MRS.EQ.0) GO TO 800
C
      NCODL=NCODA
      IF (NCODI.EQ.1) NCODL=NCODA+1
C
      IF (NCODI-1) 52,54,58
C
   52 NCODO=0
      NCODR=NCODB
      GO TO 62
   54 IF (NFLGS.EQ.2) GO TO 56
      NCODR=NCODB+1
      NCODO=1
      GO TO 62
   56 NCODR=NCODB
      NCODO=2
      GO TO 62
   58 IF (NFLGS.EQ.1) GO TO 60
      NCODR=NCODB
      NCODO=2
      GO TO 62
   60 NCODR=NCODB+1
      NCODO=1
C
   62 WRITE (NFTB) ML,MS3,MS4,MS1,MS2,MR,MS,MP,MQ,MRS,MPQ,
     1             NCODO,NCODB,NCODA
C
   64 ICP=NTABC(MS1+1)
      ICQ=NTABC(MS2+1)
      ICR=NTABC(MS3+1)
      ICS=NTABC(MS4+1)
C
   70 NTE=MPQ*NRS
      IF (NCODI.EQ.1) NTE=NPQ*NRS
      KAP=MP*NQ
      KT=MR*NS
      IF (KT.GT.KAP) KAP=KT
      KCPQ=1
      KA=KAP+1
      KB=KA+NPQ
      IF (LPRD.GT.NPQ) KB=KA+LPRD
      NCORB=NCOR-KB
      IF (NTE.GT.NCORB) GO TO 300
C
C
  100 IF (NCODL-2) 110,130,150
  110 continue
      DO 120 N=1,NRS
      READ (NFTA) (CR(KAP+I),I=1,NPQ)
      CALL NTRNQP
     *  (1,N,NP,MP,NQ,MQ,CR(KA),CR(KB),NRS,C(ICP),C(ICQ),CR(KCPQ))
  120 CONTINUE
      GO TO 200
  130 CALL READT (NFTA,NRS,CR(KB))
      MI=1
      DO 140 N=1,NRS
      CALL NTRNQP 
     *  (MI,MI,NP,MP,NQ,MQ,CR(KB),CR(KB),1,C(ICP),C(ICQ),CR(KCPQ))
  140 MI=MI+NPQ
      CALL TRNSPS (NRS,MPQ,CR(KB))
      GO TO 200
C
  150 IF (NCODL.EQ.4) GO TO 170
      DO 160 N=1,NRS
      READ (NFTA) (CR(KAP+I),I=1,NPQ)
      CALL NTRNPP 
     *  (1,N,NP,MP,CR(KA),CR(KB),NRS,C(ICP),CR(KCPQ))
  160 CONTINUE
      GO TO 200
C
  170 CALL READT (NFTA,NRS,CR(KB))
      MI=1
      DO 180 N=1,NRS
      CALL NTRNPP 
     *  (MI,MI,NP,MP,CR(KB),CR(KB),1,C(ICP),CR(KCPQ))
  180 MI=MI+NPQ
      CALL TRNSPS (NRS,MPQ,CR(KB))
C
  200 CONTINUE
      IF (NCODR-2) 210,230,250
  210 continue
      NN=NRS*MPQ
      DO 220 N=1,NN,NRS
      CALL NTRNQP 
     *  (N,1,NR,MR,NS,MS,CR(KB),CR(KA),1,C(ICR),C(ICS),CR(KCPQ))
  220 WRITE (NFTB) (CR(KAP+I),I=1,MRS)
      GO TO 290
C
  230 continue
      M=1
      DO 240 N=1,MPQ
      CALL NTRNRS 
     *  (M,N,NR,MR,NS,MS,CR(KB),CR(KA),C(ICR),C(ICS),CR(KCPQ))
      M=M+NRS
  240 WRITE (NFTB) (CR(KAP+I),I=1,N)
      GO TO 290
C
  250 IF (NCODR.EQ.4) GO TO 270
C
      NN=NRS*MPQ
      DO 260 N=1,NN,NRS
      CALL NTRNPP 
     *  (N,1,NR,MR,CR(KB),CR(KA),1,C(ICR),CR(KCPQ))
  260 WRITE (NFTB) (CR(KAP+I),I=1,MRS)
      GO TO 290
C
  270 continue
      M=1
      DO 280 N=1,MPQ
      CALL NTRNRR 
     *  (M,N,NR,MR,CR(KB),CR(KA),C(ICR),CR(KCPQ))
      M=M+NRS
      WRITE (NFTB) (CR(KAP+I),I=1,N)
  280 CONTINUE
C
  290 GO TO 50
C     CHANGED  BY M. SEKIYA   AT IMS    ON 1987-12-12
C     DA FILE INITIAL WRITE
C 300 NROW=NRS
  300 CONTINUE
      IF ( NFD .EQ. 0 ) THEN
         NALM = 5
         WRITE (6,*) ' ** UNIT NUMBER OF DA FILE IS 0 ** ERROR ** '
         RETURN
         END IF
      CALL DEFDA(NFD,LDSK)
      WRITE (6,*) ' *WARNING*  CORE IS SMALL ',
     C            '  >> TRANSFORMATION USING DA FULE << '
      NROW=NRS
      NCLM=MPQ
      NROWA=NCORB/NCLM
      NCLMA=NCORB/NROW
      NCLMC=(NCLM-1)/NCLMA
      NROWC=(NROW-1)/NROWA
      NDRPB=(NROWA*NCLMA-1)/LPRD+1
      NROWB=NROW-NROWA*NROWC
      NCLMB=NCLM-NCLMA*NCLMC
      NDRPBP=(NROWB*NCLMA-1)/LPRD+1
      NPR=NDRPB*NCLMC+(NCLMB*NROWA-1)/LPRD+1
      NPRP=NDRPBP*NCLMC+(NROWB*NCLMB-1)/LPRD+1
      IF (NCODI.EQ.1) GO TO 310
      NTDRN=NPR*NROWC+NPRP
      IF (NTDRN.LE.NTDRG) GO TO 400
      GO TO 320
C
  310 MROW=NRS
      MROWA=NCLMA
      MROWC=(MROW-1)/MROWA
      MROWB=MROW-MROWA*MROWC
      MDRPB=(MROWA*MROWA-1) /LPRD+1
      MDRPC=(MROWA*MROWB-1)/LPRD+1
      MDRPD=(MROWB*MROWB-1)/LPRD+1
      MPR=MROWC*MDRPB+MDRPC
      MPRP=MROWC*MDRPC+MDRPD
      NTDRN=MPR*MROWC+MPRP
      NROWA=NCLMA
      NPR=MDRPB*NCLMC+(NCLMB*MROWA-1)/LPRD+1
      IF (NTDRN.LE.NTDRG) GO TO 500
      GO TO 320
C
  320 WRITE (6,322)
  322 FORMAT (21H0NEED MORE DISK SPACE)
      NALM=1
      RETURN
C
  400 CALL STWDSK (NFD,     LPRD,NROWA,NCLM,NCLMA,NPR,   CR(KB),CR(KA))
      IF (NCODL.EQ.3) GO TO 450
      DO 420 L=1,NROW,NROWA
      NB=1
      LA=L+NROWA-1
      IF (LA.GT.NROW) LA=NROW
      DO 410 N=L,LA
      READ (NFTA) (CR(KAP+I),I=1,NPQ)
      CALL NTRNQP 
     *  (1,NB,NP,MP,NQ,MQ,CR(KA),CR(KB),1,C(ICP),C(ICQ),CR(KCPQ))
  410 NB=NB+NCLM
  420 CALL WDSK (L,LA)
      GO TO 600
C
  450 continue
      DO 470 L=1,NROW,NROWA
      NB=1
      LA=L+NROWA-1
      IF (LA.GT.NROW) LA=NROW
      DO 460 N=L,LA
      READ (NFTA) (CR(KAP+I),I=1,NPQ)
      CALL NTRNPP
     *  (1,NB,NP,MP,CR(KA),CR(KB),1,C(ICP),CR(KCPQ))
  460 NB=NB+NCLM
  470 CALL WDSK (L,LA)
      GO TO 600
C
  500 CALL WTRIAG (NFTA,NFD,     LPRD,MROW,MROWA,MPR,CR(KA),CR(KB))
      CALL PRTRAG (NFD,     LPRD,MROW,MROWA,
     1             MPR,MDRPB,CR(KA),CR(KB))
      CALL STWDSK (NFD,     LPRD,NROWA,NCLM,NCLMA,NPR,CR(KB),CR(KA))
      IF (NCODL.EQ.4) GO TO 550
C
      DO 530 L=1,NROW,NROWA
      LA=L+NROWA-1
      IF (LA.GT.NROW) LA=NROW
      NA=1
      NB=1
      CALL RTRIAG (L,LA)
      DO 520 N=L,LA
      CALL NTRNQP 
     *  (NA,NB,NP,MP,NQ,MQ,CR(KB),CR(KB),1,C(ICP),C(ICQ),CR(KCPQ))
      NA=NA+NPQ
  520 NB=NB+MPQ
  530 CALL WDSK (L,LA)
      GO TO 600
C
  550 continue
      DO 570 L=1,NROW,NROWA
      LA=L+NROWA-1
      IF (LA.GT.NROW) LA=NROW
      NA=1
      NB=1
      CALL RTRIAG (L,LA)
      DO 560 N=L,LA
      CALL NTRNPP 
     *  (NA,NB,NP,MP,CR(KB),CR(KB),1,C(ICP),CR(KCPQ))
      NA=NA+NPQ
  560 NB=NB+MPQ
  570 CALL WDSK (L,LA)
C
  600 CALL STRDSK (NFD,     LPRD,NROW,NROWA,NCLMA,NPR,CR(KA),CR(KB))
      IF (NCODR-2) 630,640,610
  610 IF (NCODR.EQ.4) GO TO 620
C
      GO TO 650
  620 continue
      GO TO 650
  630 continue
      GO TO 650
  640 continue
C
  650 DO 750 L=1,NCLM,NCLMA
      LA=L+NCLMA-1
      IF (LA.GT.NCLM) LA=NCLM
      CALL RDSK (L,LA)
      NB=1
      IF (NCODR-2) 660,680,700
  660 DO 670 N=L,LA
      CALL NTRNQP 
     *  (NB,1,NR,MR,NS,MS,CR(KB),CR(KA),1,C(ICR),C(ICS),CR(KCPQ))
      WRITE (NFTB) (CR(KAP+I),I=1,MRS)
  670 NB=NB+NROW
      GO TO 750
C
  680 DO 690 N=L,LA
      CALL NTRNRS 
     *  (NB,N,NR,MR,NS,MS,CR(KB),CR(KA),C(ICR),C(ICS),CR(KCPQ))
      WRITE (NFTB) (CR(KAP+I),I=1,N)
  690 NB=NB+NROW
      GO TO 750
C
  700 IF (NCODR.EQ.4) GO TO 720
      DO 710 N=L,LA
      CALL NTRNPP 
     *  (NB,1,NR,MR,CR(KB),CR(KA),1,C(ICR),CR(KCPQ))
      WRITE (NFTB) (CR(KAP+I),I=1,MRS)
  710 NB=NB+NROW
      GO TO 750
C
  720 DO 730 N=L,LA
      CALL NTRNRR 
     *  (NB,N,NR,MR,CR(KB),CR(KA),C(ICR),CR(KCPQ))
      WRITE (NFTB) (CR(KAP+I),I=1,N)
  730 NB=NB+NROW
C
  750 CONTINUE
C
      GO TO 50
  800 DO 810 N=1,NRS
  810 READ (NFTA)
      GO TO 50
C
  900 NALM=0
      RETURN
      END
C*DECK TRNSH
      SUBROUTINE TRNSH (LMAX,NBF,NOB,C,NFTA,NFTB,LTRI,NCOR,NR,CR,NALM)
C                                 CHECKED TASHI 10/25/89 HUCC
      IMPLICIT REAL*8 (A-H,O-Z)
      DIMENSION NBF(*),NOB(*),NR(*),CR(*),C(*)
C
  100 KTB=0
      NTB=LMAX+1
      MTB=LMAX+NTB+1
      NALM=0
      ND=0
      NR(KTB+1)=1
      DO 110 L=1,LMAX
      NR(NTB+L)=(NBF(L)*(NBF(L)+1))/2
      ND=ND+NR(NTB+L)
      NR(MTB+L)=(NOB(L)*(NOB(L)+1))/2
  110 NR(KTB+L+1)=NR(KTB+L)+NBF(L)*NOB(L)
C
      KS=(MTB+LMAX+1)/2+2
      KSB=KS+ND
      KTP=KSB+ND
      LST=KTP+2*ND
      IF (LST.LE.NCOR) GO TO 1000
C
      NALM=1
      WRITE (6,120)
  120 FORMAT ('1 NEED MORE SPACE IN TRNSH')
      GO TO 9999
C
 1000 DO 1020 L=1,LMAX
      IF (NBF(L).EQ.0) GO TO 1020
      NT=NR(NTB+L)
      CALL RDSH (1,L,NT,CR(KS),NFTA,LTRI,NALM)
      IF (NALM.NE.0) GO TO 9999
      IF (NOB(L).EQ.0) GO TO 1020
C
      CALL  NTRNPP 
     *  (1,1,NBF(L),NOB(L),CR(KS),CR(KSB),1,C(NR(KTB+L)),CR(KTP))
      NT=NR(MTB+L)
      CALL WRTSH(1,L,NT,CR(KSB),NFTB,LTRI,NALM)
      IF (NALM.NE.0) GO TO 9999
 1020 CONTINUE
C
 1100 DO 1120 L=1,LMAX
      IF (NBF(L).EQ.0) GO TO 1120
      NT=NR(NTB+L)
      CALL RDSH (2,L,NT,CR(KS),NFTA,LTRI,NALM)
      IF (NALM.NE.0) GO TO 9999
      IF (NOB(L).EQ.0) GO TO 1120
C
      CALL NTRNPP 
     *  (1,1,NBF(L),NOB(L),CR(KS),CR(KSB),1,C(NR(KTB+L)),CR(KTP))
      NT=NR(MTB+L)
      CALL WRTSH(2,L,NT,CR(KSB),NFTB,LTRI,NALM)
      IF (NALM.NE.0) GO TO 9999
 1120 CONTINUE
 9999 RETURN
      END
