C*DECK EXIJ
      SUBROUTINE EXIJ
     1          ( JA, JJ,
     2            IA, II,
     3            NWFSG,
     4            NOET,N1OET,NOEC,N1OEC,
     5            NPFLG,RTNCD,
     6            nwt,NWF,NWTH,NWTC)
C
C/*   FUNCTION : ENERGY EXPRESSION FOR JA+1 TO JA+NSJ & IA+1 TO IA + NSI
C/*   CALLED   : EXTAPE
C/*   CALLING  : SMAT
C/*              STORE
C/*              SETBIT
C/*              BIT
C/*          JA <= IA  ASSUMED
C                                 CHECKED TASHI 10/25/89 HUCC
      IMPLICIT REAL*8(A-H,O-Z)
      dimension nwth(nwt),nwtc(nwf)
      include 'include/COMEXP'
      INTEGER   * 4 IBIT(25,800)
      INTEGER   * 4 BIT
      INTEGER   * 2 NWFSG(*)
C     INTEGER   * 4 IWAD(12),IVAD(12),IWVAD(130)
      INTEGER   * 4 RTNCD
C     IDIAG=1  FOR JA = IA JJ=II
      NOEX= 0
      IDIAG = 0
      IF ( JA.EQ.IA .AND. JJ.EQ.II ) IDIAG = 1
      NSJ=NWFSG(JJ)
      NJRPS=NWFSG(JJ+1)
      JNEN=JJ+2
      JNEQ=JNEN+NSJ
      JNESL=JNEQ+NSJ
 2201 NSI=NWFSG(II)
      NIRPS=NWFSG(II+1)
      INEN=II+2
      INEQ=INEN+NSI
      INESL=INEQ+NSI
      DO 2000 JT=1,NJRPS
C========CONVERTED,BEGIN====(CV.NO. 000001 ,DATE 78-08-24 19:00:00'=====
CC    DO 2000 I=1,4
      DO 2000 I=1,25
C========CONVERTED,END==================================================
 2000 IBIT(I,JT)=0
      JTR=1
      ITR=1
 2100 IREM=0
      IKRPS=INESL+NSI*ITR
      JKRPS=JNESL+NSJ*JTR
      IF ( NOEX .GT. 0 ) CALL STOREH(NOEX,RTNCD)
      CALL SMAT(NSI,NWFSG(INEN),NWFSG(INEQ),NWFSG(INESL),NWFSG(IKRPS),
     1    NSJ,NWFSG(JNEN),NWFSG(JNEQ),NWFSG(JNESL),NWFSG(JKRPS),
     2    NOE,N1OE,NHT,NFS,NHDT,NSIT,NSJT,
     6            nwt,NWF,NWTH,NWTC)
      IF(NPFLG.GT.2)  WRITE(6,9500) IWAD,IVAD,IWVAD
 9500 FORMAT(7H IWAD =,12I5/7H IVAD =,12I5,/7H IWVAD=,20I5/
     1  6(7X,20I5/))
      IF(NPFLG.GT.2)  WRITE(6,9501) NSI,NSIT,NSJ,NSJT
     *   ,  NOE, N1OE,  IA, JA, ITR, JTR
 9501 FORMAT(7H  NSI =,I5,8H  NSIT =,I5,9H    NSJ =,I6,8H  NSJT =,I5/,
     3  7H  NOE =,I5,8H  N1OE =,I5,8H    IA =,I7,6H  JA =,I7,7H  ITR =,
     4  I5,7H  JTR =, I5)
      NOEX = NOE
      NOEC=NOEC+NOE
      N1OEC=N1OEC+N1OE
      JT=JTR
 2010 CONTINUE
      JADT=JNESL+NSJ*JT-1
      IT=1
      IF(IDIAG.EQ.2) IT=JT
 2021 CONTINUE
      IF(IDIAG.EQ.1) JT=IT
      IF(BIT(IBIT(1,JT),IT).NE.0) GO TO 2022
      IADT=INESL+IT*NSI-1
      DO 2030 IWT=1,NSIT
      KT=IWAD(IWT)
 2030 IWVAD(KT)=NWFSG(IWT+IADT)
      IF(IDIAG.EQ.1) GO TO 2050
      DO 2031 JWT=1,NSJT
      KT=IVAD(JWT)
      IF(IWVAD(KT).EQ.NWFSG(JWT+JADT))GO TO 2031
      IF(KT.NE.130) GO TO 2023
 2031 CONTINUE
      IF(NHT.LE.1) GO TO 2040
      DO 2041 K=2,NHT
      IF(IWVAD(K-1).GE.IWVAD(K)) GO TO 2023
 2041 CONTINUE
 2040 IF(NFS.LE.1)  GO TO 2050
      DO 2051 K=2,NFS
      IF(IWVAD(K+99).GE.IWVAD(K+100)) GO TO 2023
 2051 CONTINUE
 2050 CONTINUE
      IF(NOE.EQ.0) GO TO 2060
      IF(NHDT.NE.0) GO TO 2205
      IF(IA+IT.EQ.JA+JT) GO TO 2205
      GOTO 9000
 2205 CONTINUE
      CALL STORE(NOE,N1OE,IA+IT,JA+JT)
      NOET=NOET+NOE
      N1OET=N1OET+N1OE
 2060 CALL SETBIT(IBIT(1,JT),IT)
      GO TO 2022
 2023 IF(IREM.EQ.1) GO TO 2022
      IREM=1
      JTR=JT
      ITR=IT
 2022 IT=IT+1
      IF(IT.LE.NIRPS) GO TO 2021
      IF(IDIAG.NE.1.OR.NJRPS.EQ.1) GO TO 2029
      IDIAG=2
      JTR=1
      ITR=2
      GO TO 2100
 2029 CONTINUE
      JADT=JADT+NSJ
      DO 2070 JWT=1,NSJT
      KT=IVAD(JWT)
 2070 IWVAD(KT)=NWFSG(JWT+JADT)
      JT=JT+1
      IF(JT.LE.NJRPS) GO TO 2010
      IF(IREM.EQ.1) GO TO 2100
 2211 CONTINUE
      IF ( NOEX .GT. 0 ) CALL STOREH(NOEX,RTNCD)
      RETURN
 9000 CONTINUE
      JA = JA + JT
      IA = IA + IT
      RTNCD = 9999
      RETURN
      END
