C*DECK MJCDG
      SUBROUTINE MJCDG(VC,EPS,H,N,IVCF,NSOLVE,ISOLVE,
     *  BIG,JBIG,OMIT,  CONV,MXNI,  IRTNCD)
C     SUBROUTINE JCDG(VC,EPS,H,N,IVCF,NSOLVE,ISOLVE,*,*)
C
C                    CHANGED  BY F. SASAKI    1994-01-29 AT HU
C                             entries JCDGAR,JCDGST moved to main call
C                    CHANGED  BY M. SEKIYA ON 1987-12-12 AT IMS
C                    CHANGED  BY TASHI     ON 1989-10-25 AT HUCC
C     JCDG IS A JACOBI DIAGONALIZATION ROUTINE WHICH SOLVES
C                             HU = EUD
C         CALLING SEQUENCE PARAMETERS ARE AS FOLLOWS
C              VC   LOCATION OF AN N*N(R*8) ARRAY WHICH WILL CONTAIN
C                   ORDERED EIGENVECTORS -- INITIAL CONDITION OF VC
C                   GIVEN BY VALUE OF IVCF
C              EPS  LOCATION OF AN   N REAL*8 ARRAY WHERE ORDERED
C                   EIGENVALUES ARE TO BE STORED
C              H    LOCATION OF MATRIX(WHICH IS DESTROYED DURING
C                   DIAGONALIZATION) STORED TRIANGULAR N*(N+1)12 ARRAY
C              N    DIMENSION OF MATRIX
C              IVCF IVCF .LE. 0 VC ARE NOT PRESET
C                   IVCF .GE. 1 VC ARE PRESET TO AN ORTHONORMAL SET
C                               H MATRIX IS ASSUMED TO BE H = UHU
C              NSOLVE    NUMBER OF VECTORS AND VALUES TO BE DETERMINED
C                        IF NSOLVE = 0 FULL DIAGONALIZATION IS PERFORMED
C              ISOLVE    LIST OF NSOLVE INDICES GIVING VECTORS TO BE
C                        SOLVED FOR
C                        IF NSOLVE = 0, ISOLVE LIST IS IGNORED
C         RETURNS
C              NORMAL RETURN  CONVERGED RESULTS OBTAINED
C              RETURN 1       CONVERGED RESULTS NOT OBTAINED
C                        INCOMPLETE RESULTS ARE IN H VC AND EPS
C                        ARRAYS
C              GOTO 9999       CHANGED  BY M. SEKIYA ON 1987-12-12
C              RETURN 2       ERROR OR INCONSISTENT INFORMATION IN
C                        PARAMETERS OF THE CALLING SEQUENCE
C              RETURN 1 ---> irtncd = 8450
C              RETURN 2 ---> irtncd = 8451
C
C     AUXILLIARY ENTRIES
C     ENTRY JCDGAR (BIG,JBIG,OMIT)
C         THIS ENTRY SETS ARRAYS DEFINED EXTERNALLY WHICH HAVE DIM OF BF
C              BIG       CONTAINS LARGEST O-D ELEMENT OF EACH ROW
C              JBIG      CONTAINS COLUMN INDEX OF ENTRIES IN ARRAY BIG
C              OMIT      IF TRUE DO NOT OBTAIN THIS EIGENVALUE/VECTOR
C                        (L*1 ARRAY)
C         ALL THESE ARRAYS ARE JCDG PROGRAM WORK AREAS
C              INITIAL VALUES ARE NOT REQUIRED
C     ENTRY JCDGST (CONV,MXNI)
C              CONV      CONVERGENCE THRESHOLD TO BE USED (REAL*8)
C                        A WORKING CONSTANT CONVW IS SET FROM CONV AND
C                        DEFAULT VALUES
C                        CMIN LE CONVW LE CMAX, IF(CONV=0) CONVW=CSTAN
C                        OTHERWISE CONVW = CONV
C              MXNI      MAXIMUM NUMBER OF ITERATIONS TO BE PERFORMED
C                        A WORKING CONSTANT MXNIW IS SET FROM MXNI AND
C                        DEFAULT VALUES
C                        MXNIW = FFFFFF (2B20-1) IF MXNI LE 0 OTHERWISE
C                        MXNIW = MXNI
C     ENTRY JCDGQU (NIEX,CONVEX,MXNIEX)
C         THIS ENTRY QUERIES VALUES OF LOCAL CONVERGENCE CONSTANTS
C              NIEX      SET TO VALUE OF NI USED FOR LAST DIAG
C              CONVEX    SET TO VALUE OF CONVW (MAY BE R*4 OR R*8)
C              MXNIEX    SET TO VALUE OF MXNIW
C     ENTRY JCDGOR (REOREX)   REOREX(LOGICAL) SET TO TRUE IF REORDERING OF
C                             EPS AND VC DONE IN LAST DIAG
C
      IMPLICIT REAL*8 (A-H,O-Z)
      DIMENSION VC(N,N), EPS(*), H(*), ISOLVE(*)
C     REAL*4        CONV, CONVW, CONVEX
C        changed to real*8    SAS   94/01/29
      LOGICAL     REOREX, OMIT
C     EXTERNAL ARRAYS WITH BASIS FUNCTIONS DIMENSIONS
      DIMENSION BIG(*),  JBIG(*),  OMIT(*)
C     LOCAL CONSTANT POOL
      LOGICAL     REORD,TEST
C
C     REAL*4 CSTAN/Z38100000/, CMIN/Z3B100000/, CMAX/Z36100000/
      REAL*8 CSTAN, CMIN, CMAX
      SAVE
C     DATA VALUES   REDF = 2B-4  THR1 = 2B43  THR2 = 2B-8  THR3 = 2B-23
C                   THR4 = 2B-12
C     DATA  DMIN/1.D-4/, REDF/Z4010000000000000/
C     DATA  THR1, THR2, THR3, THR4
C    1    /Z4B80000000000000, Z3F10000000000000, Z3B20000000000000,
C    2     Z3E10000000000000/
C     DATA   MXNIBG /ZFFFFFF/
C     DATA   CSTAN/Z38100000/, CMIN/Z3B100000/, CMAX/Z36100000/
      DATA  DMIN/1.D-4/
C     DATA  REDF/Z'4010000000000000'/
C     DATA  THR1, THR2, THR3
C    1/Z'4B80000000000000',Z'3F10000000000000',Z'3B20000000000000'/
C     DATA  THR4 /Z'3E10000000000000'/
C     DATA   MXNIBG /Z'FFFFFF'/
C     DATA   CSTAN/Z'3810000000000000'/, CMIN/Z'3B10000000000000'/
C     DATA   CMAX/Z'3610000000000000'/
      data cstan/ 0.14551915228367d-10/,cmin/ 0.59604644775391d-07/
      data cmax/ 0.56843418860808d-13/,thr1/ 0.87960930222080d+13/
      data thr2/ 0.39062500000000d-02/,thr3/ 0.11920928955078d-06/
      data thr4/ 0.24414062500000d-03/,redf/ 0.62500000000000d-01/
C
C     data cstan/ 0.11754943508223d-37/,cmin / 0.33087224502121d-23/
C     data cmax / 0.27369110631344d-47/,thr1 / 0.49039857307708d+56/
C     data thr2 / 0.61035156250000d-04/,thr3 / 0.66174449004242d-23/
C     data thr4 / 0.93132257461548d-09/,redf / 0.40000000000000d+01/
      data mxnibg/  16777215/
C
C     GO TO 77777
C
C     ENTRY TO SET EXTERNAL ARRAYS WITH BASIS FUNCTION ARRAYS
C
C     ENTRY JCDGAR (BIG,JBIG,OMIT)
C     RETURN
C
C     ENTRY TO SET CONVW MXNIW AND ROOT2
C
C     ENTRY JCDGST (CONV,MXNI)
      MXNIW = MXNI
      IF (MXNIW .LE. 0) MXNIW = MXNIBG
      CONVW = CONV
      IF (CONVW .LE. 0.) CONVW = CSTAN
      CONVW = MAX (MIN(CONVW,CMIN), CMAX)
      CONV8 = CONVW
      ROOT2 = DSQRT(0.5D0)
C     RETURN
      go to 77777
C
C     ENTRY TO QUERY NI, CONVW, AND MXNIW
C
      ENTRY JCDGQU (NIEX,CONVEX,MXNIEX)
      NIEX = NI
      CONVEX = CONVW
      MXNIEX = MXNIW
      RETURN
C
C     ENTRY TO QUERY REORD
C
C           checked and save added    94/01/29
C
      ENTRY JCDGOR (REOREX)
      REOREX = REORD
      RETURN
77777 CONTINUE
C
C     IF DIMENSION IS LE 0 MAKE AN ERROR EXIT
      IF (N .LE. 0) GOTO 9999
C     SET VALUES OF REORD AND NI (FOR N=1 EXIT)
      REORD = .FALSE.
      NI = 1
      IF (IVCF .GT. 0) GO TO 9
      DO 5 I=1,N
      DO 4 J=1,N
    4 VC(J,I) = 0.D0
    5 VC(I,I) = 1.D0
C
C     MOVE DIAGONAL ELEMENTS OF MATRIX TO ARRAY EPS
C
    9 J = 0
      DO 10 I=1,N
      J = J+I
   10 EPS(I) = H(J)
      IF (N .EQ. 1) RETURN
C
C     FORM LOGICAL VECTOR OMIT WITH OMIT(I) EQUALS TRUE FOR EACH
C         EIGENVECTOR AND VALUE WHICH IS NOT TO BE SOLVED FOR
C              NSOLVE GIVES THE NUMBER OF ENTRIES IN OMIT TO BE
C                        SET TO FALSE
C                   ISOLVE IS A LIST OF INDICES WHICH IDENTIFIES THE
C                        FALSE ENTRIES
C              IF NSOLVE IS 0 ILIST IS NOT EXAMINED AND ALL ENTRIES
C                        IN OMIT ARE SET TO FALSE
C
      TEST = .TRUE.
      IF (NSOLVE .LE. 0) TEST = .FALSE.
      DO 15 I=1,N
   15 OMIT(I) = TEST
      IF (NSOLVE .LE. 0) GO TO 23
      IF (NSOLVE .GT. N) GOTO 9999
      DO 21 I=1,NSOLVE
      IF (ISOLVE(I) .GT. N  .OR.  ISOLVE(I) .LE. 0) GOTO 9999
      OMIT(ISOLVE(I)) = .FALSE.
      IF (I .EQ. 1) GO TO 21
      J = I-1
      DO 20 K=1,J
      IF (ISOLVE(I) .EQ. ISOLVE(K)) GOTO 9999
   20 CONTINUE
   21 CONTINUE
C
C
C     FORM THE REAL*8 VECTOR BIG AND THE INTEGER VECTOR JBIG
C              BIG(I) CONTAINS THE VALUE OF LARGEST OFF-DIAGONAL
C                   ELEMENT OF ROW I
C              JBIG(I) CONTAINS THE COLUMN INDEX OF THE ELEMENT IN
C                   BIG(I)
C              IF NO OFF-DIAGONAL ELEMENTS OF ROW I ARE TO BE EXAMINED
C                   BIG(I) AND JBIG ARE SET TO ZERO
C
   23 IEAR = 1
      BIG(1) = 0.D0
      JBIG(1) = 0
      DO 30 I=2,N
      BIG(I) = 0.D0
      JBIG(I) = 0
      J = I-1
      DO 25 K=1,J
      IF (DABS(BIG(I)) .GE. DABS(H(IEAR+K))) GO TO 25
      IF ( OMIT(I) .AND. OMIT(K) ) GO TO 25
      BIG(I) = H(IEAR+K)
      JBIG(I) = K
   25 CONTINUE
   30 IEAR = IEAR + I
C
C                        *****     *****     *****
C     BEGIN MAIN TRANSFORMATION LOOP
C                        *****     *****     *****
C
      DO 135 NI = 1,MXNIW
C
C     FIND SMALLEST DIAGONAL ELEMENT OR DMIN WHICHEVER IS SMALLER
C         IF ONLY SOME OF THE VECTORS ARE BEING SOUGHT THE MINIMUM
C         DIAGONAL ELEMENT IS REDUCED BY REDF TO ALLOW FOR POSSIBLE
C         CONTAMINATION FROM UNKOWN EIGENVECTORS
C         HOWEVER ONLY IN THE IMPROBABLE CASE THAT ONE OF THE SOUGHT
C         EIGENVALUES IS NEARLY DEGENERATE WITH AN UNKNOWN VALUE
C         THAT THIS IS AT ALL RELEVANT
C
      DO 35 I=1,N
      IF (.NOT. OMIT(I)) GO TO 40
   35 CONTINUE
   40 SD = DABS (EPS(I))
      DO 45 J=I,N
      IF (SD .GT. DABS(EPS(J)) .AND.  .NOT. OMIT(J)) SD = DABS(EPS(J))
   45 CONTINUE
      IF (NSOLVE .NE. 0) SD = SD*REDF
      SD = DMAX1 (SD,DMIN)
C
C         FIND THE LARGEST OFF-DIAGONAL ELEMENT AND IT'S INDICES
C
      T =0.D0
      DO 50 I=2,N
      IF (T .GE. DABS(BIG(I)))GO TO 50
      T = DABS(BIG(I))
      IB = I
      IA = JBIG(I)
   50 CONTINUE
C
C     TEST FOR CONVERGENCE AND SKIP OUT
C
      IF (T .LE. CONV8*SD) GO TO 140
C
C     EVALUATE TRIGONOMETRIC FUNCTIONS
C
      SX = ROOT2
      CX = ROOT2
C     IF TAN2X/2 GE THR1 SET SX=CX=1/SQRT(2)
      IF ( DABS(EPS(IA)-EPS(IB)) .LE. 1.D-37) GO TO 70
      T2X2 = BIG(IB)/(EPS(IA)-EPS(IB))
      ABST = DABS(T2X2)
      IF (ABST       .GE. THR1) GO TO 70
C
C     IF TAN2X/2 GT THR2 SKIP TO USE FULL SIN/COS FORMULAS
C
      IF (ABST       .GT. THR2) GO TO 65
C
C     IF TAN2X/2 LE THR3 USE COSX=1 AND SINX=TAN2X/2
C
      IF (ABST       .GT. THR3) GO TO 55
      CX = 1.D0
      SX = T2X2
      GO TO 70
C
C     USE EXPANSION FORMULAS FOR SIN AND COS
C
   55 T2X25 = ABST*ABST
      IF (ABST       .GT. THR4) GO TO 60
      CX = 1.D0 - 0.5D0*T2X25
      SX = T2X2*(1.D0 -1.5D0*T2X25)
      GO TO 70
   60 CX = 1.D0 + T2X25 * (T2X25*1.375D0-0.5D0)
      SX = T2X2 * (1.D0 +T2X25*(T2X25*3.875D0-1.5D0))
      GO TO 70
   65 T = 0.25D0/DSQRT(0.25D0 + ABST*ABST)
      CX = DSQRT(.5D0 + T)
      SX = DSQRT(.5D0 - T)
      SX = DSIGN(SX,T2X2)
C
C     COMPUTE TRANSTORMED ME OF H AND RESET VECTORS BIG AND JBIG
C
C     LOCATE FIRST ELEMENTS OF A ROW AND B ROW
   70 IEAR = (IA*(IA-1))/2+1
      IEBR = (IB*(IB-1))/2+1
      DO 125 IR=1,N
      T = H(IEAR)*SX
      H(IEAR) = H(IEAR)*CX + H(IEBR)*SX
      H(IEBR) = T - H(IEBR)*CX
C
C     TEST FOR A ROW OR DIAGONAL ELEM A OR A COLUMN
C
      IF (IR-IA) 120,75,80
C
C     FINISH PROCESSING OF A ROW FOR DIAGONAL ELEMENT
C
C     SAVE PARTIAL C ELEM FOR LATER USE
   75 TT = H(IEBR)
      IEAA = IEAR
      IEAB = IEBR
      H(IEBR) = BIG(IB)
      IEAR = IEAR+IR-1
C
C     SKIP OVER BIG AND JBIG RESETTING IF NOT REQUIRED
C
      IF (JBIG(IR) .EQ. 0) GO TO 120
      GO TO 110
C
C     COMPLETE A COLUMN PROCESSING
C
   80 T = H(IEAR)
      IT = IA
      IF (.NOT.OMIT(IA) .OR. .NOT.OMIT(IR)) GO TO 82
      T = 0.D0
      IT = 0
   82 IEAR = IEAR+IR-1
C
C     TEST FOR B ROW OR DIAGONAL ELEM B OR B COLUMN
C
      IF (IR-IB) 100,85,90
C
C     FINISH PROCESSING ELEMENTS A, B, AND C
C
   85 H(IEAA) = H(IEAA)*CX + H(IEAB)*SX
      EPS(IA) = H(IEAA)
      H(IEAB) = TT*CX + H(IEBR)*SX
      H(IEBR) = TT*SX - H(IEBR)*CX
      EPS(IB) = H(IEBR)
      IEBR = IEBR+IR-1
      GO TO 110
C
C     COMPLETE B COLUMN PROCESSING
C
   90 IF (DABS(T) .GE. DABS(H(IEBR))) GO TO 95
      IF (OMIT(IB) .AND. OMIT(IR)) GO TO 95
      T = H(IEBR)
      IT = IB
   95 IEBR = IEBR+IR-1
C
C     RESET BIG(IR) AND JBIG(IR)
C
  100 IF (DABS(T) .LT. DABS(BIG(IR))) GO TO 105
      BIG(IR) = T
      JBIG(IR) = IT
      GO TO 120
  105 IF (IA .NE. JBIG(IR) .AND. IB .NE. JBIG(IR)) GO TO 120
C
C     RESEARCH ENTIRE IR ROW TO RESET ]IG(IR) AND JBIG(IR)
C
C     LOCATE FIRST ELEMENT OF IR ROW MINUS 2
  110 K = IEAR - IR - IA + 2
      BIG(IR) = 0.D0
      IR1 = IR - 1
      DO 115 I=1,IR1
      IF (DABS(BIG(IR)) .GE. DABS(H(K))) GO TO 115
      IF (OMIT(IR) .AND. OMIT(I)) GO TO 115
      BIG(IR) = H(K)
      JBIG(IR) = I
  115 K = K+1
  120 IEAR = IEAR + 1
  125 IEBR = IEBR + 1
C
C     COMPUTE NEW UNITARY TRANSFORMATION
C
      DO 130 I=1,N
      T = VC(I,IB)*SX
      VC(I,IB) = VC(I,IA)*SX - VC(I,IB)*CX
  130 VC(I,IA) = VC(I,IA)*CX + T
  135 CONTINUE
      NI = MXNIW + 1
C         CHANGED  BY M. SEKIYA ON 1987-12-12 AT IMS
C     RETURN 1       CONVERGED RESULTS NOT OBTAINED
C                    INCOMPLETE RESULTS ARE IN H VC AND EPS ARRAYS
C           CONVERGENCE FAILED
      WRITE (6,*) ' >> CONVERGENCE FAILED IN JCDG << '
      IRTNCD = 8450
      RETURN
C
C                        *****     *****     *****
C     BEGIN FINAL LOOP -- REORDER EIGNVECTORS AND EIGNVALUES
C                        *****     *****     +****
C
  140 DO 155 I=1,N
      IF (OMIT(I)) GO TO 155
      JJ = I
      DO 145 J=I,N
      IF (EPS(J) .LT. EPS(JJ)  .AND.  .NOT.OMIT(J)) JJ = J
  145 CONTINUE
C
C     IF NO REORDERING REQUIRED SKIP OVER
C
      IF (JJ .EQ. I) GO TO 155
C     REORDER VALUES AND VECTORS
      T = EPS(JJ)
      EPS(JJ) = EPS(I)
      EPS(I)  = T
      REORD = .TRUE.
      DO 150 J=1,N
      T = VC(J,JJ)
      VC(J,JJ) = VC(J,I)
  150 VC(J,I)  = T
  155 CONTINUE
      RETURN
C        CHANGED  BY M. SEKIYA AT IMS    ON 1987-12-12
C         RETURN 2       ERROR OR INCONSISTENT INFORMATION IN
C                        PARAMETERS OF THE CALLING SEQUENCE
C          RETURN 2 -> GOTO 9999
 9999 WRITE(6,*) ' *ERROR* IN JCDG >>> INCONSISTENT INFORMATION IN ',
     *           ' PARAMETERS OF THE CALLING SEQUENCE '
      IRTNCD = 8451
      RETURN
      END
