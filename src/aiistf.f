C*DECK AIISTF
      SUBROUTINE AIISTF (NRDFG,NMODFG,NFTD,LOEI,NWT,NAME,Z,IDPRNT,
     1  IIPRNT,NWLF,DEL,NPQN,LMAX,INXT,ISSH,IFST)
C        REVISED BY MAS ADDING NPQN & DEL  AT IMS  ON 1988-03-01
C        REVISED BY TASHI                  AT HUCC ON 1989-10-25
      IMPLICIT REAL*8(A-H,O-Z)
      DIMENSION NWLF(150),DEL(150),NPQN(150),DOP(150),INXT(150)
      dimension ISSH(20),IFST(20),ICRNT(20)
C       ,FAC(57),
      include 'include/COMWIG'
      dimension NAME(33),BUFF(1600),ITAD(20)
      DIMENSION MPOB(150),MOB(150)
      character * 1 lett
      DATA IBUFF/1600/
      CALL CLOCKM(ITIN)
      CALL MODORB(NMODFG,DEL)
      IF(NMODFG.EQ.0) GO TO 1
      GO TO 1233
    1 CONTINUE
      CALL IRDSET(IDPRNT)
      DO 2 I=1,20
      IFST(I)=0
    2 ISSH(I)=0
      DO 3 I=1,150
   3  INXT(I)=0
      I=0
      LMAX=0
  124 call readia ( np, lett )
      if ( lett .eq. ')' ) go to 123
      call readia ( k, lett )
      call dcoda  ( lett, k )	 
      if ( k .eq. 0 ) go to 9000
C     CALL IREAD(NP,*123)
C     CALL IREAD(K,*9000)
C     CALL DCOD (K,*9000)
      I=I+1
      K=K/2+1
      LMAX=MAX0(K,LMAX)
C     CALL FREAD(DEL(I),*9000)
      call  readfa ( del(i), lett )
      if (lett .ne. ',' )  go to 9000
      IF(ISSH(K).EQ.0) GO TO 121
      J=ICRNT(K)
      INXT(J)=I
      GO TO 122
  121 IFST(K)=I
  122 ICRNT(K)=I
      ISSH(K)=ISSH(K)+1
      NWLF(I)=K
      NPQN(I)=NP
      GO TO 124
 9000 WRITE(6,9001)
 9001 FORMAT('0BASORB FORMAT ERROR     ERROR   *****************')
      CALL NEWCD
      GO TO 124
C*KGN JULY 20/90
* 123 IF(I.NE.NWT) WRITE(6,9002) I,NWT
 9002 FORMAT('0BASORB INPUT ERROR  NWTX =',I5,5X,'NWT =',I5,'   ERROR*')
  123 NWT=I
      CALL NEWCD
 1233 CONTINUE
C     FAC(1)=1.0D0
C     A=0.0D0
C     DO 1231 I=1,56
C     A=A+1.0D0
C1231 FAC(I+1)=FAC(I)*A
C     AT=  QFGF3(FAC)
      LMAXX=LMAX-1
      WRITE(6,1220) NAME,NWT,NFTD,LOEI,LMAXX,Z
 1220 FORMAT(///' INPUT BASORB       NAME',/'0',33A4/'0NWT   =',I5,6X,
     1  'NFTD  =',I5,6X,'LOEI  =',I5,6X,'LMAXX =',I5,6X,'Z   =',F17.10)
C*KGN  SUPPRESS THE MESSAGE
*     WRITE(6,1221) (ISSH(I),I=1,LMAX)
*     WRITE(6,1222) (IFST(I),I=1,LMAX)
 1221 FORMAT('0ISSH  =',20I6)
 1222 FORMAT('0IFST  =',20I6)
      WRITE(6,1223) (I,NPQN(I),NWLF(I),INXT(I),DEL(I),I=1,NWT)
 1223 FORMAT('0',4('     I  N  L  NXT    DELTA       ')//(I7,2I3,I5,
     1  F16.11,I6,2I3,I5,F16.11,I6,2I3,I5,F16.11,I6,2I3,I5,F16.11))
      K=0
      DO 131 I=1,LMAX
      JMAX=ISSH(I)
      IF(JMAX.EQ.0) GO TO 131
      DO 132 J=1,JMAX
      K=K+1
      MPOB(K)=J
      MOB(K)=I-1
  132 CONTINUE
  131 CONTINUE
      I1=1
      Z0=0.0D0
C*KGN  SUPPRESS THE MESSAGE
*     WRITE(6,1224) (MPOB(I),I=1,NWT)
*     WRITE(6,1225)  (MOB(I),I=1,NWT)
 1225 FORMAT('0MOB   =',20I6/(8X,20I6))
 1224 FORMAT('0MPOB  =',20I6/(8X,20I6))
      WRITE(NFTD) NAME,LMAX,NWT,I1,I1,LOEI,(ISSH(I),I=1,LMAX),
     1  (MPOB(I),I=1,NWT),(MOB(I),I=1,NWT),Z,Z0,
     2  (NPQN(I),I=1,NWT),(DEL(I),I=1,NWT)
C        REVISED BY MAS ADDING NPQN & DEL  AT IMS ON 1988-03-01
      DO 143 I=1,NWT
      IQ=NPQN(I)
      DI=DEL(I)
  143 DOP(I)=DSQRT((DI+DI)**(1+2*IQ)/FAC(1+2*IQ))
      DO 152 L=1,LMAX
      IMAX=ISSH(L)
      IST=0
      IF(IMAX.EQ.0) GO TO 152
      IF(IMAX*(IMAX+1).GT.2*IBUFF) GO TO 9005
      IAD=IFST(L)
  155 IQ=NPQN(IAD)
      DI=DEL(IAD)
      JAD=IFST(L)
  154 JQ=NPQN(JAD)
      DJ=DEL(JAD)
      IST=IST+1
      IJQ=IQ+JQ
      BUFF(IST)=FAC(IJQ+1)*DOP(IAD)*DOP(JAD)/((DI+DJ)**(IJQ+1))
      IF(JAD.EQ.IAD) GO TO 153
      JAD=INXT(JAD)
      GO TO 154
  153 IAD=INXT(IAD)
      IF(IAD.NE.0) GO TO 155
      M=L-1
      ITYP=1
      IMIN=1
 1551 IMAX=MIN0(IMIN+LOEI-1,IST)
      LCL=IMAX-IMIN+1
      WRITE(NFTD) ITYP,L,LCL,(BUFF(I),I=IMIN,IMAX)
      IF(IIPRNT.GT.4) WRITE(6,8000) ITYP,L,LCL,(BUFF(I),I=IMIN,IMAX)
      IMIN=IMAX+1
      IF(IMIN.LE.IST) GO TO 1551
  152 CONTINUE
      IGTAD=0
      ITAD(1)=0
      DO 162 L=1,LMAX
      IMAX=ISSH(L)
      IST=0
      IF(IMAX.EQ.0) GO TO 1621
      IAD=IFST(L)
  165 IQ=NPQN(IAD)
      DI=DEL(IAD)
      JAD=IFST(L)
  164 JQ=NPQN(JAD)
      DJ=DEL(JAD)
      IJQ=IQ+JQ
      DIJ=DI+DJ
      IST=IST+1
      BUFF(IST)=(FAC(IJQ-1)*DFLOAT((IQ-1)*(JQ-1)+L*(L-1))/DIJ**(IJQ-1)
     1  -(DI*DFLOAT(JQ-1)+DJ*DFLOAT(IQ-1)+Z+Z)*FAC(IJQ)/DIJ**IJQ
     2  +DI*DJ*FAC(IJQ+1)      /DIJ**(IJQ+1))*DOP(IAD)*DOP(JAD)*0.5D0
      IF(JAD.EQ.IAD) GO TO 163
      JAD=INXT(JAD)
      GO TO 164
  163 IAD=INXT(IAD)
      IF(IAD.NE.0) GO TO 165
      M=L-1
      ITYP=2
      IMIN=1
 1651 IMAX=MIN0(IMIN+LOEI-1,IST)
      LCL=IMAX-IMIN+1
      WRITE(NFTD) ITYP,L,LCL,(BUFF(I),I=IMIN,IMAX)
      IF(IIPRNT.GT.4) WRITE(6,8000) ITYP,L,LCL,(BUFF(I),I=IMIN,IMAX)
 8000 FORMAT(3I8,6E17.7/(24X,6E17.7))
      IMIN=IMAX+1
      IF(IMIN.LE.IST) GO TO 1651
 1621 IF(L.GT.1) ITAD(L)=(LMAX-L+2)*(  L-1)+ITAD(L-1)
      IGTAD=IGTAD+IST
  162 CONTINUE
      KMAX=2*LMAX-1
      IF(IDPRNT.NE.0) WRITE(6,9998)
 9998 FORMAT('0     KM     LN1  LN2  LN3  LN4    IDIMA    IDIMB'
     1   ,'    IGTAD'/)
      IADMAX=0
      DO 191 KM=1,KMAX
      KPT=MOD(KM+1,2)+1
      ISAD=0
      DO 192 IDA=KPT,LMAX,2
      IF(IDA.GT.KM) GO TO 191
      DO 193 ITA=IDA,KMAX,2
      IF(ITA.LT.KM) GO TO 193
      LN1=(IDA+ITA)/2
      IF(LN1.GT.LMAX) GO TO 192
      LN2=(ITA-IDA)/2+1
      KT=(ITA-KM)/2
      IAD=ITAD(LN2)+KT*(LMAX-LN2+1)+IDA
      IADMAX=MAX0(IAD,IADMAX)
      IDIMA=ISSH(LN1)*ISSH(LN2)
      IF(IDA.EQ.1) IDIMA=(ISSH(LN1)*(ISSH(LN1)+1))/2
      ISAD=ISAD+IDIMA
      DO 194 IDB=KPT,IDA,2
      ITBG=KMAX
      IF(IDB.EQ.IDA) ITBG=ITA
      DO 195 ITB=IDB,ITBG,2
      IF(ITB.LT.KM) GO TO 195
      LN3=(IDB+ITB)/2
      IF(LN3.GT.LMAX) GO TO 194
      LN4=(ITB-IDB)/2+1
      IDIMB=ISSH(LN3)*ISSH(LN4)
      IF(IDB.EQ.1) IDIMB=(ISSH(LN3)*(ISSH(LN3)+1))/2
      IDIM= IDIMA*IDIMB
      IF(IDA.EQ.IDB.AND.ITA.EQ.ITB) IDIM=(IDIMA*(IDIMA+1))/2
      IF(IDPRNT.NE.0) WRITE(6,9999) KM,LN1,LN2,LN3,LN4,IDIMA,IDIMB,IGTAD
 9999 FORMAT(2I8,3I5,3I9)
      IF(IDIM.EQ.0) GO TO 195
      NCODA=1
      NCODB=1
      NCODI=0
      IF(LN1.EQ.LN2) NCODA=3
      IF(LN3.EQ.LN4) NCODB=3
      IF(IDA.EQ.IDB.AND.ITA.EQ.ITB) NCODI=1
      KMM1=KM-1
      LK1=LN1-1
      LK2=LN2-1
      LK3=LN3-1
      LK4=LN4-1
      WRITE(NFTD) KMM1,LK1,LK2,LK3,LK4,ISSH(LN1),ISSH(LN2),ISSH(LN3),
     1  ISSH(LN4),IDIMA,IDIMB,NCODI,NCODA,NCODB
      KRD=IFST(LN4)
  214 IQR=NPQN(KRD)
      DQR=DEL(KRD)
      KSD=IFST(LN3)
  213 IQS=NPQN(KSD)
      DQS=DEL(KSD)
      AO=DOP(KRD)*DOP(KSD)
      IST=0
      KPD=IFST(LN2)
  212 IQP=NPQN(KPD)
      DQP=DEL(KPD)
      KQD=IFST(LN1)
  211 IQQ=NPQN(KQD)
      DQQ=DEL(KQD)
      IST=IST+1
      IF(IST.GT.IBUFF) GO TO 9005
      BUFF(IST)=FGF3(IQP+IQQ,IQR+IQS,  KM-1,DQP+DQQ,DQR+DQS)*
     1  AO*DOP(KPD)*DOP(KQD)
      KQD=INXT(KQD)
      IF(KQD.EQ.0) GO TO 201
      IF(NCODI.EQ.1.AND.KPD.EQ.KRD.AND.KQD.GT.KSD) GO TO 201
      IF(LN1.EQ.LN2.AND.KQD.GT.KPD) GO TO 201
      GO TO 211
  201 KPD=INXT(KPD)
      IF(KPD.EQ.0) GO TO 202
      IF(NCODI.EQ.1.AND.KPD.GT.KRD) GO TO 202
      GO TO 212
  202 WRITE(NFTD) (BUFF(I),I=1,IST)
      IF(IIPRNT.GT.4) WRITE(6,8001) (BUFF(I),I=1,IST)
 8001 FORMAT(8E16.7)
      IGTAD=IGTAD+IST
      KSD=INXT(KSD)
      IF(KSD.EQ.0) GO TO 203
      IF(LN3.EQ.LN4.AND.KSD.GT.KRD) GO TO 203
      GO TO 213
  203 KRD=INXT(KRD)
      IF(KRD.NE.0) GO TO 214
  195 CONTINUE
  194 CONTINUE
  193 CONTINUE
  192 CONTINUE
  191 CONTINUE
C     WRITE(6,9004) IADMAX,IGTAD
C9004 FORMAT('0IADMAX=',I7,7X,'IGTAD =',I7)
      WRITE(6,9004) IGTAD
 9004 FORMAT('0IGTAD =',I10)

  300 CALL CLOCKM(ITOUT)
      TT=DFLOAT(ITOUT-ITIN)/1000.0D0
      WRITE(6,500) TT
  500 FORMAT('0PROGRAM INTLST      USED TIME =', F7.2,' SEC')
      RETURN
 9005 WRITE(6,9006) IBUFF
 9006 FORMAT('0IBUFF TOO SMALL     IBUFF =',I7,7X,'ERROR  *********')
      GO TO 300
      END
