C
C ## C(NL,MX) <--- C(MX,NL) ##
C ## D(NL,MX) <--- D(MX,NL) ##
C
      SUBROUTINE REVRS2(A,B,C,D,MX)
C
      IMPLICIT REAL*8(A-H,O-Z)
C
      COMMON/COMPRM/IND(100),NL,NS,M,M2,M1,M12,IT,IPS,IO,IOA,IOB,IOF,ICV
C
      DIMENSION A(NL,*),B(NL,*)
      DIMENSION C(MX,*),D(MX,*)
C
      DO 200 I=1,MX
      DO 200 K=1,NL
  200 B(K,I)=D(I,K)
C
      DO 100 I=1,MX
      DO 100 K=1,NL
  100 A(K,I)=C(I,K)
C
      RETURN
      END
C*DECK REVRS3
C
C ## C(NL,M2) <--- C(M2,NL) ##
C ## D(NL,M2) <--- D(M2,NL) ##
C
      SUBROUTINE REVRS3(A,B,C,D,W,BB)
C
      IMPLICIT REAL*8(A-H,O-Z)
C
      COMMON/COMPRM/IND(100),NL,NS,M,M2,M1,M12,IT,IPS,IO,IOA,IOB,IOF,ICV
C
      DIMENSION A(NL,*),B(NL,*)
      DIMENSION C(M2,*),D(M2,*)
      DIMENSION W(NL,*),BB(*)
C
      WRITE(IOF) NL,M,((D(I,K),K=1,NL),I=1,M)
      REWIND IOF
C
      DO 300 I=1,M12
      DO 300 K=1,NL
  300 W(K,I)=D(I+M,K)
C
      DO 200 I=1,M2
      DO 200 K=1,NL
  200 A(K,I)=C(I,K)
C
      DO 100 I=1,M12
      DO 100 K=1,NL
  100 B(K,I+M)=W(K,I)
C
      READ(IOF) NL,M,(BB(KI),KI=1,NL*M)
      REWIND IOF
C
      RETURN
      END
