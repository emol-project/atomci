C*DECK QAFACT
C     SUBROUTINE QAFACT(ISB,IRB,RT)
      SUBROUTINE AFACT(ISB,IRB,
     *   N1,N2,L,LS,LR,M,JM,JNUM,JS,JR,KM,KS,KR,C,   W)
C                                 CHECKED TASHI 10/25/89 HUCC
      IMPLICIT  REAL*8(A-H,O-Z)
      include 'include/COMWIG'
C     DIMENSION RT(2),ISB(2),IRB(2),JNUM(5)
      DIMENSION ISB(2),IRB(2),JNUM(5)
      DIMENSION JM(5),KM(5),JS(6),JR(6),KS(6),KR(6)
      SAVE ITSTA
      EXTERNAL IOR,ISP
      ZP(I)=DFLOAT(1-2*IABS(MOD((I+8888)/2,2)))
C
      DATA ITSTA/0/
C           L     M.GT.N1.  M.EQ.N1  M.LT.N1
C        M.GT.N2     1        4        7
C        M.EQ.N2     2        5        8
C        M.LT.N2     3        6        9
C
C     ENTRY QAFACT(ISB,IRB,RT)
C     ITEST=1
C     RETURN
C
      W=0.0D0
      K=M+1
      GO TO (7,11,7,11,8,8,7,8,9),L
    7 IF(JM(M)-KM(M)) 10,11,10
    8 IF(IABS(JS(M)-KS(M))+IABS(JR(M)-KR(M))) 10,11,10
    9 IF(JM(M)-KM(M)) 10,8,10
   11 ISX=ISP(JM(M))
      IRX=IOR(JM(M))
      KSX=ISP(KM(M))
      KRX=IOR(KM(M))
      GO TO (21,22,23,24,25,26,27,28,29),L
   29 IF(IABS(JS(K)-KS(K))+IABS(JR(K)-KR(K)))10,35,10
   35 W=1.0D0
   10 GO TO 1000
   21 JST=LS
      JRT=LR
      J=0
      GO TO 30
   23 JST=ISB(N1)
      JRT=IRB(N1)
      GO TO 31
   27 JST=ISB(N2)
      JRT=IRB(N2)
   31 J=2*JNUM(M)
   30 W=ZP(JST+JRT+J+JS(M+1)+JR(M+1)+KS(M)+KR(M)+ISP(JM(M))+IOR(JM(M)))
     1  *DSQRT(DFLOAT(JS(M+1)*JR(M+1)*KS(M)*KR(M)))*
     2   WIG6J(ISX,JS(M),JS(M+1),JST,KS(M+1),KS(M))*
     6   WIG6J(IRX,JR(M),JR(M+1),JRT,KR(M+1),KR(M))
      GO TO 1000
   25 JST=LS
      JRT=LR
      W=C*  RT(JST+1)*RT(JRT+1)
   33 W=W*ZP(JST+JRT+JS(M)+JR(M)+KS(M+1)+KR(M+1)+ISX+IRX)*
     1   DSQRT(DFLOAT(JS(M+1)*JR(M+1)))*
     2   WIG6J(JST,ISX,KSX,JS(M),KS(M+1),JS(M+1))*
     3   WIG6J(JRT,IRX,KRX,JR(M),KR(M+1),JR(M+1))
      GO TO 1000
   26 W=C
   32 JST=ISB(M)
      JRT=IRB(M)
      GO TO 33
   28 W=C
      GO TO 32
   22 JST=ISB(N1)
      JRT=IRB(N1)
      W=-ZP(JST-JRT+ISB(M)-IRB(M)-LS+LR)*C
      GO TO 34
   24 JST=ISB(N2)
      JRT=IRB(N2)
      W=C
   34 ISM=ISB(M)
      IRM=IRB(M)
      W=W*ZP(2*JNUM(M))   *DSQRT(DFLOAT(LS*LR*JS(M+1)*JR(M+1)*KS(M)*
     1  KR(M)))*WIG9X(ISM,JST,LS,ISX,JS(M),JS(M+1),KSX,KS(M),KS(M+1))*
     2          WIG9X(IRM,JRT,LR,IRX,JR(M),JR(M+1),KRX,KR(M),KR(M+1))
 1000 IF(ITSTA.NE.0) WRITE(6,9500) N1,N2,L,LS,LR,M,JM,JNUM,JS,JR,
     1   KM,KS,KR,C,W
 9500 FORMAT(' AFACT ',6I6,2X,5I6,2X,5I6/7X,6I6,2X,6I6,2X,5I6/
     1   7X,6I6,2X,6I6,2F21.13)
      RETURN
C
      ENTRY TAFACT(IFACT)
      ITSTA=IFACT
      RETURN
      END
